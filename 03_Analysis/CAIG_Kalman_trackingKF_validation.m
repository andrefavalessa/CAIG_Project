function Omega = generateLevel2Sway(t)

    % Zhang level-2 sea-condition sway parameters.
    %
    % Exact waveform is not given by Zhang.
    % Sinusoidal attitude motion remains the project assumption.

    rollAmp = ...
        deg2rad(0.50);

    pitchAmp = ...
        deg2rad(0.20);

    headingAmp = ...
        deg2rad(0.30);

    rollPeriod = ...
        20;

    pitchPeriod = ...
        30;

    headingPeriod = ...
        30;

    wr = ...
        2*pi/rollPeriod;

    wp = ...
        2*pi/pitchPeriod;

    wh = ...
        2*pi/headingPeriod;

    roll = ...
        rollAmp ...
        *sin(wr*t);

    pitch = ...
        pitchAmp ...
        *sin(wp*t);

    rollDot = ...
        rollAmp ...
        *wr ...
        *cos(wr*t);

    pitchDot = ...
        pitchAmp ...
        *wp ...
        *cos(wp*t);

    headingDot = ...
        headingAmp ...
        *wh ...
        *cos(wh*t);

    % 3-2-1 Euler-angle rates -> body rates

    p = ...
        rollDot ...
        -headingDot.*sin(pitch);

    q = ...
        pitchDot.*cos(roll) ...
        +headingDot.*sin(roll).*cos(pitch);

    r = ...
        -pitchDot.*sin(roll) ...
        +headingDot.*cos(roll).*cos(pitch);

    Omega = ...
        [p q r];

end


function S = skewMatrix(v)

    v = ...
        v(:);

    S = ...
        [ ...
             0,     -v(3),   v(2);
             v(3),   0,     -v(1);
            -v(2),   v(1),   0
        ];

end


function text = passFail(condition)

    if condition

        text = ...
            'PASS';

    else

        text = ...
            'CHECK';

    end

end