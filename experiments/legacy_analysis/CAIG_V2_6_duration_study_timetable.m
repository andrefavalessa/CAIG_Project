%% ============================================================
% LOCAL FUNCTIONS
% =============================================================

function Omega = generateLevel2Sway(t)

    % Zhang level-2 sway parameters:
    %
    % Roll:
    %   amplitude = 0.50 deg
    %   period    = 20 s
    %
    % Pitch:
    %   amplitude = 0.20 deg
    %   period    = 30 s
    %
    % Heading:
    %   amplitude = 0.30 deg
    %   period    = 30 s
    %
    % Zhang provides amplitudes and periods but does not
    % provide the exact time-domain waveform.
    %
    % Sinusoidal motion is therefore a project assumption.

    rollAmp = ...
        deg2rad(0.50);

    pitchAmp = ...
        deg2rad(0.20);

    headingAmp = ...
        deg2rad(0.30);

    rollPeriod = ...
        20;

    pitchPeriod = ...
        30;

    headingPeriod = ...
        30;

    wr = ...
        2*pi/rollPeriod;

    wp = ...
        2*pi/pitchPeriod;

    wh = ...
        2*pi/headingPeriod;

    roll = ...
        rollAmp ...
        * sin(wr*t);

    pitch = ...
        pitchAmp ...
        * sin(wp*t);

    rollDot = ...
        rollAmp ...
        * wr ...
        * cos(wr*t);

    pitchDot = ...
        pitchAmp ...
        * wp ...
        * cos(wp*t);

    headingDot = ...
        headingAmp ...
        * wh ...
        * cos(wh*t);

    % 3-2-1 Euler-angle rates -> body angular rates
    %
    % p = phidot - psidot*sin(theta)
    %
    % q = thetadot*cos(phi)
    %     + psidot*sin(phi)*cos(theta)
    %
    % r = -thetadot*sin(phi)
    %     + psidot*cos(phi)*cos(theta)

    p = ...
        rollDot ...
        - headingDot ...
        .* sin(pitch);

    q = ...
        pitchDot ...
        .* cos(roll) ...
        ...
        + headingDot ...
        .* sin(roll) ...
        .* cos(pitch);

    r = ...
        -pitchDot ...
        .* sin(roll) ...
        ...
        + headingDot ...
        .* cos(roll) ...
        .* cos(pitch);

    Omega = ...
        [p q r];

end


function S = skewMatrix(v)

    % Return [v x] such that
    %
    % [v x] a = v x a

    v = ...
        v(:);

    S = ...
        [ ...
             0,     -v(3),   v(2);
             v(3),   0,     -v(1);
            -v(2),   v(1),   0 ...
        ];

end