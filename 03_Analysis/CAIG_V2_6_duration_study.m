%% CAIG_V2_6_duration_study.m
%
% Observation-duration study for the noisy CAIG + FOG
% six-state Kalman estimator.
%
% Main architecture:
%   Zhang et al. (2019)
%
% The purpose is to evaluate how increasing the available
% observation duration affects estimation of:
%
%   - CAIG/FOG frame misalignment
%   - constant FOG bias
%
% Durations:
%   120 s
%   300 s
%   600 s
%
% Monte Carlo:
%   100 runs per duration
%
%
% UPDATED FOG NOISE MODEL
% -----------------------
%
% EMCORE EG-1300:
%
%   ARW = 0.002 deg/sqrt(h)
%
% The FOG now uses:
%
%   NoiseType = 'single-sided'
%
% consistent with the MathWorks Allan-variance
% parameter-scaling workflow validated separately.
%
%
% CAIG NOISE MODEL
% ----------------
%
% Tackmann et al. (2012):
%
%   sensitivity = 6.1e-7 rad/s/sqrt(Hz)
%
% Current project baseline:
%
%   sigma_CAIG = N_CAIG * sqrt(Fs_CAIG/2)
%
% This remains an explicit modeling assumption.

clear;
clc;
close all;

%% ============================================================
% 1. GENERAL SETTINGS
% =============================================================

durations = [120 300 600];     % [s]

nRuns = 100;

FsFOG  = 100;                  % [Hz] Zhang
FsCAIG = 5;                    % [Hz] Zhang

sampleRatio = FsFOG/FsCAIG;

assert(mod(sampleRatio,1) == 0, ...
    'FOG/CAIG sample-rate ratio must be integer.');

fprintf('============================================\n');
fprintf('CAIG V2.6 - DURATION STUDY\n');
fprintf('============================================\n\n');

fprintf('Monte Carlo runs = %d\n', nRuns);
fprintf('FOG rate         = %.1f Hz\n', FsFOG);
fprintf('CAIG rate        = %.1f Hz\n', FsCAIG);

fprintf('Durations        = ');
fprintf('%.0f ', durations);
fprintf('s\n\n');

%% ============================================================
% 2. TRUE MISALIGNMENT
% =============================================================

phiTrueDeg = [1; 2; 3];

phiTrue = ...
    deg2rad(phiTrueDeg);

C_A_F = ...
    eye(3) - skewMatrix(phiTrue);

%% ============================================================
% 3. TRUE FOG BIAS
% =============================================================

biasFOG_deg_h = 0.1;

biasFOG = ...
    deg2rad(biasFOG_deg_h)/3600;

biasFOGvec = ...
    biasFOG*ones(1,3);

%% ============================================================
% 4. FOG WHITE NOISE
% =============================================================

% EMCORE EG-1300
ARW_FOG_deg_sqrt_h = 0.002;

N_FOG = ...
    deg2rad(ARW_FOG_deg_sqrt_h) ...
    / sqrt(3600);

% Corrected single-sided mapping
sigmaFOG = ...
    N_FOG * sqrt(FsFOG);

fprintf('FOG NOISE MODEL\n');
fprintf('--------------------------------------------\n');

fprintf('ARW         = %.6f deg/sqrt(h)\n', ...
    ARW_FOG_deg_sqrt_h);

fprintf('NoiseType   = single-sided\n');

fprintf('N_FOG       = %.6e rad/s/sqrt(Hz)\n', ...
    N_FOG);

fprintf('sigma_FOG   = %.6e rad/s\n\n', ...
    sigmaFOG);

%% ============================================================
% 5. CAIG WHITE NOISE
% =============================================================

% Tackmann et al. (2012)
N_CAIG = 6.1e-7;       % rad/s/sqrt(Hz)

% Current project baseline convention
sigmaCAIG = ...
    N_CAIG * sqrt(FsCAIG/2);

fprintf('CAIG NOISE MODEL\n');
fprintf('--------------------------------------------\n');

fprintf('N_CAIG      = %.6e rad/s/sqrt(Hz)\n', ...
    N_CAIG);

fprintf('sigma_CAIG  = %.6e rad/s\n\n', ...
    sigmaCAIG);

%% ============================================================
% 6. OBSERVATION COVARIANCE
% =============================================================

sigmaZ = ...
    sqrt( ...
        sigmaFOG^2 ...
        + sigmaCAIG^2);

R = ...
    sigmaZ^2 * eye(3);

fprintf('OBSERVATION NOISE\n');
fprintf('--------------------------------------------\n');

fprintf('sigma_Z     = %.6e rad/s\n', ...
    sigmaZ);

fprintf('R diagonal  = %.6e (rad/s)^2\n\n', ...
    R(1,1));

%% ============================================================
% 7. KALMAN INITIAL CONDITIONS
% =============================================================

X0 = ...
    zeros(6,1);

phiStd0 = ...
    deg2rad([1;2;3]);

biasStd0 = ...
    deg2rad([0.1;0.1;0.1])/3600;

P0 = ...
    diag([phiStd0; biasStd0].^2);

Phi = ...
    eye(6);

% True simulated states remain constant
Q = ...
    zeros(6);

I6 = ...
    eye(6);

%% ============================================================
% 8. STORAGE FOR DURATION RESULTS
% =============================================================

nDur = ...
    length(durations);

meanPhi_all = ...
    zeros(nDur,3);

stdPhi_all = ...
    zeros(nDur,3);

rmsePhi_all = ...
    zeros(nDur,3);

ciPhiLow_all = ...
    zeros(nDur,3);

ciPhiHigh_all = ...
    zeros(nDur,3);


meanBias_all = ...
    zeros(nDur,3);

stdBias_all = ...
    zeros(nDur,3);

rmseBias_all = ...
    zeros(nDur,3);

ciBiasLow_all = ...
    zeros(nDur,3);

ciBiasHigh_all = ...
    zeros(nDur,3);

%% ============================================================
% 9. LOOP OVER OBSERVATION DURATIONS
% =============================================================

for d = 1:nDur

    duration = ...
        durations(d);

    fprintf('============================================\n');
    fprintf('DURATION = %.0f s\n', duration);
    fprintf('============================================\n');

    %% --------------------------------------------------------
    % Time vectors
    % ---------------------------------------------------------

    dtFOG  = 1/FsFOG;
    dtCAIG = 1/FsCAIG;

    tFOG = ...
        (0:dtFOG:duration-dtFOG).';

    tCAIG = ...
        (0:dtCAIG:duration-dtCAIG).';

    NFOG = ...
        length(tFOG);

    NCAIG = ...
        length(tCAIG);

    idxCAIGinFOG = ...
        1:sampleRatio:NFOG;

    %% --------------------------------------------------------
    % Ground-truth triaxial sway
    % ---------------------------------------------------------

    OmegaA_FOG = ...
        generateLevel2Sway(tFOG);

    OmegaA_CAIG = ...
        generateLevel2Sway(tCAIG);

    % Express true angular rate in FOG frame
    OmegaF_true = ...
        (C_A_F * OmegaA_FOG.').';

    %% --------------------------------------------------------
    % Storage for this duration
    % ---------------------------------------------------------

    finalStates = ...
        zeros(nRuns,6);

    %% --------------------------------------------------------
    % Monte Carlo
    % ---------------------------------------------------------

    for run = 1:nRuns

        % ====================================================
        % FOG realization
        % ====================================================

        % Same seed per run across durations.
        %
        % Therefore, shorter simulations correspond to the
        % initial portion of the longer noise realizations.
        %
        % This makes duration comparisons approximately paired.

        rng(10000 + run, 'twister');

        paramsFOG = ...
            gyroparams( ...
                'ConstantBias', ...
                biasFOGvec, ...
                ...
                'NoiseDensity', ...
                N_FOG*ones(1,3), ...
                ...
                'NoiseType', ...
                'single-sided');

        imuFOG = ...
            imuSensor( ...
                'accel-gyro', ...
                ...
                'SampleRate', ...
                FsFOG, ...
                ...
                'Gyroscope', ...
                paramsFOG);

        accelDummy = ...
            zeros(NFOG,3);

        [~, OmegaFOG] = ...
            imuFOG( ...
                accelDummy, ...
                OmegaF_true);

        OmegaFOG_CAIG = ...
            OmegaFOG(idxCAIGinFOG,:);

        % ====================================================
        % CAIG realization
        % ====================================================

        rng(20000 + run, 'twister');

        caigNoise = ...
            sigmaCAIG ...
            * randn(NCAIG,3);

        OmegaCAIG = ...
            OmegaA_CAIG ...
            + caigNoise;

        % ====================================================
        % Monitoring observation
        % ====================================================

        Z = ...
            OmegaFOG_CAIG ...
            - OmegaCAIG;

        % ====================================================
        % Kalman initialization
        % ====================================================

        Xhat = ...
            X0;

        P = ...
            P0;

        % ====================================================
        % Kalman loop
        % ====================================================

        for k = 1:NCAIG

            % -----------------------------------------------
            % Prediction
            % -----------------------------------------------

            Xpred = ...
                Phi*Xhat;

            Ppred = ...
                Phi*P*Phi.' ...
                + Q;

            % -----------------------------------------------
            % Measurement matrix
            % -----------------------------------------------

            % Use true simulation angular rate in H.
            %
            % This isolates the Zhang linear observation model
            % from errors-in-variables effects.

            omega = ...
                OmegaA_CAIG(k,:).';

            H = ...
                [ ...
                    skewMatrix(omega), ...
                    eye(3) ...
                ];

            % -----------------------------------------------
            % Innovation
            % -----------------------------------------------

            z = ...
                Z(k,:).';

            innovation = ...
                z ...
                - H*Xpred;

            % -----------------------------------------------
            % Innovation covariance
            % -----------------------------------------------

            S = ...
                H*Ppred*H.' ...
                + R;

            % -----------------------------------------------
            % Kalman gain
            % -----------------------------------------------

            K = ...
                Ppred*H.'/S;

            % -----------------------------------------------
            % State update
            % -----------------------------------------------

            Xhat = ...
                Xpred ...
                + K*innovation;

            % -----------------------------------------------
            % Joseph covariance update
            % -----------------------------------------------

            P = ...
                (I6-K*H) ...
                * Ppred ...
                * (I6-K*H).' ...
                ...
                + K*R*K.';

        end

        finalStates(run,:) = ...
            Xhat.';

    end

    %% --------------------------------------------------------
    % Convert Monte Carlo results
    % ---------------------------------------------------------

    phiEstDeg = ...
        rad2deg( ...
            finalStates(:,1:3));

    biasEstDeg_h = ...
        rad2deg( ...
            finalStates(:,4:6)) ...
        *3600;

    truePhi = ...
        phiTrueDeg.';

    trueBias = ...
        biasFOG_deg_h*ones(1,3);

    %% --------------------------------------------------------
    % Misalignment statistics
    % ---------------------------------------------------------

    meanPhi = ...
        mean(phiEstDeg,1);

    stdPhi = ...
        std(phiEstDeg,0,1);

    rmsePhi = ...
        sqrt( ...
            mean( ...
                (phiEstDeg-truePhi).^2, ...
                1));

    ciPhiLow = ...
        meanPhi ...
        - 1.96*stdPhi/sqrt(nRuns);

    ciPhiHigh = ...
        meanPhi ...
        + 1.96*stdPhi/sqrt(nRuns);

    %% --------------------------------------------------------
    % Bias statistics
    % ---------------------------------------------------------

    meanBias = ...
        mean(biasEstDeg_h,1);

    stdBias = ...
        std(biasEstDeg_h,0,1);

    rmseBias = ...
        sqrt( ...
            mean( ...
                (biasEstDeg_h-trueBias).^2, ...
                1));

    ciBiasLow = ...
        meanBias ...
        - 1.96*stdBias/sqrt(nRuns);

    ciBiasHigh = ...
        meanBias ...
        + 1.96*stdBias/sqrt(nRuns);

    %% --------------------------------------------------------
    % Save duration results
    % ---------------------------------------------------------

    meanPhi_all(d,:) = ...
        meanPhi;

    stdPhi_all(d,:) = ...
        stdPhi;

    rmsePhi_all(d,:) = ...
        rmsePhi;

    ciPhiLow_all(d,:) = ...
        ciPhiLow;

    ciPhiHigh_all(d,:) = ...
        ciPhiHigh;


    meanBias_all(d,:) = ...
        meanBias;

    stdBias_all(d,:) = ...
        stdBias;

    rmseBias_all(d,:) = ...
        rmseBias;

    ciBiasLow_all(d,:) = ...
        ciBiasLow;

    ciBiasHigh_all(d,:) = ...
        ciBiasHigh;

    %% --------------------------------------------------------
    % Print duration results
    % ---------------------------------------------------------
    axesNames = {'X','Y','Z'};
    fprintf('\nMISALIGNMENT\n');
    
    for ax = 1:3
    
        fprintf( ...
            '%s: mean = %.6f deg | std = %.6f | RMSE = %.6f\n', ...
            axesNames{ax}, ...
            meanPhi(ax), ...
            stdPhi(ax), ...
            rmsePhi(ax));
    
    end

    fprintf('\nFOG BIAS\n');
    
    for ax = 1:3
    
        fprintf( ...
            '%s: mean = %.6f deg/h | std = %.6f | RMSE = %.6f\n', ...
            axesNames{ax}, ...
            meanBias(ax), ...
            stdBias(ax), ...
            rmseBias(ax));
    
        fprintf( ...
            '   95%% CI mean = [%.6f, %.6f] deg/h\n', ...
            ciBiasLow(ax), ...
            ciBiasHigh(ax));
    
    end
    
    fprintf('\n');


end

%% ============================================================
% 10. FINAL SUMMARY TABLE
% =============================================================

fprintf('============================================\n');
fprintf('FINAL DURATION SUMMARY - FOG BIAS\n');
fprintf('============================================\n\n');

for d = 1:nDur

    fprintf('Duration = %.0f s\n', durations(d));

    fprintf( ...
