%% CAIG_Kalman_trackingKF_validation.m
%
% =============================================================
% VALIDATION: MANUAL ZHANG KALMAN vs MATLAB trackingKF
% =============================================================
%
% Purpose:
%
% Run two linear Kalman filters in parallel:
%
%   1) Current manual implementation
%   2) MATLAB trackingKF
%
% Both filters receive EXACTLY the same:
%
%   - synthetic FOG data
%   - synthetic CAIG data
%   - measurement z_k
%   - measurement matrix H_k
%   - X0
%   - P0
%   - Phi
%   - Q
%   - R
%
% Therefore any difference between the two filters should be
% purely numerical / implementation-level.
%
%
% Zhang state:
%
% X =
%
% [phi_x phi_y phi_z eps_Fx eps_Fy eps_Fz]^T
%
%
% IMPORTANT:
%
% This script does NOT change the scientific model.
%
% trackingKF is used only as MATLAB's implementation of the
% same linear Kalman recursion.

clear;
clc;
close all;

%% ============================================================
% 0. CHECK MATLAB trackingKF AVAILABILITY
% =============================================================

if isempty(which('trackingKF'))

    error([ ...
        'trackingKF was not found. ', ...
        'Check that Sensor Fusion and Tracking Toolbox ', ...
        'is installed and licensed.']);

end

fprintf('============================================\n');
fprintf('MANUAL KALMAN vs MATLAB trackingKF\n');
fprintf('============================================\n\n');

fprintf('trackingKF found:\n');
fprintf('%s\n\n',which('trackingKF'));

%% ============================================================
% 1. SETTINGS
% =============================================================

rng default;

duration = ...
    120;                 % [s]

FsFOG = ...
    100;                 % [Hz]

FsCAIG = ...
    5;                   % [Hz]

dtFOG = ...
    1/FsFOG;

dtCAIG = ...
    1/FsCAIG;

tFOG = ...
    (0:dtFOG:duration-dtFOG).';

tCAIG = ...
    (0:dtCAIG:duration-dtCAIG).';

NFOG = ...
    length(tFOG);

NCAIG = ...
    length(tCAIG);

timeFOG = ...
    seconds(tFOG);

timeCAIG = ...
    seconds(tCAIG);

fprintf('Duration        = %.1f s\n',duration);
fprintf('FOG rate        = %.1f Hz\n',FsFOG);
fprintf('CAIG rate       = %.1f Hz\n',FsCAIG);
fprintf('FOG samples     = %d\n',NFOG);
fprintf('CAIG samples    = %d\n\n',NCAIG);

%% ============================================================
% 2. ZHANG LEVEL-2 TRIAXIAL SWAY
% =============================================================

OmegaA_FOG = ...
    generateLevel2Sway(tFOG);

OmegaA_CAIG = ...
    generateLevel2Sway(tCAIG);

fprintf('MAXIMUM TRUE BODY RATES\n');
fprintf('--------------------------------------------\n');

fprintf('X = %.6f deg/s\n', ...
    max(abs(rad2deg(OmegaA_CAIG(:,1)))));

fprintf('Y = %.6f deg/s\n', ...
    max(abs(rad2deg(OmegaA_CAIG(:,2)))));

fprintf('Z = %.6f deg/s\n\n', ...
    max(abs(rad2deg(OmegaA_CAIG(:,3)))));

%% ============================================================
% 3. TRUE MISALIGNMENT
% =============================================================

phiTrueDeg = ...
    [1;2;3];

phiTrue = ...
    deg2rad(phiTrueDeg);

C_A_F = ...
    eye(3) ...
    -skewMatrix(phiTrue);

OmegaF_true = ...
    ( ...
        C_A_F ...
        *OmegaA_FOG.' ...
    ).';

%% ============================================================
% 4. TRUE FOG BIAS
% =============================================================

biasFOG_deg_h = ...
    0.1;

biasFOG = ...
    deg2rad(biasFOG_deg_h) ...
    /3600;

biasFOGvec = ...
    biasFOG ...
    *ones(1,3);

%% ============================================================
% 5. FOG NOISE
% =============================================================

% EMCORE EG-1300 project baseline

ARW_FOG_deg_sqrt_h = ...
    0.002;

N_FOG = ...
    deg2rad(ARW_FOG_deg_sqrt_h) ...
    /sqrt(3600);

% Allan-validated MATLAB scaling

sigmaFOG = ...
    N_FOG ...
    *sqrt(FsFOG);

fprintf('FOG MODEL\n');
fprintf('--------------------------------------------\n');

fprintf('Bias        = %.6f deg/h\n', ...
    biasFOG_deg_h);

fprintf('ARW         = %.6f deg/sqrt(h)\n', ...
    ARW_FOG_deg_sqrt_h);

fprintf('NoiseType   = single-sided\n');

fprintf('sigma_FOG   = %.6e rad/s\n\n', ...
    sigmaFOG);

%% ============================================================
% 6. GENERATE FOG USING imuSensor
% =============================================================

paramsFOG = ...
    gyroparams( ...
        'ConstantBias', ...
        biasFOGvec, ...
        ...
        'NoiseDensity', ...
        N_FOG*ones(1,3), ...
        ...
        'NoiseType', ...
        'single-sided');

imuFOG = ...
    imuSensor( ...
        'accel-gyro', ...
        ...
        'SampleRate', ...
        FsFOG, ...
        ...
        'Gyroscope', ...
        paramsFOG);

accelDummy = ...
    zeros(NFOG,3);

[~,OmegaFOG] = ...
    imuFOG( ...
        accelDummy, ...
        OmegaF_true);

%% ============================================================
% 7. CAIG NOISE
% =============================================================

N_CAIG = ...
    6.1e-7;              % [rad/s/sqrt(Hz)]

sigmaCAIG = ...
    N_CAIG ...
    *sqrt(FsCAIG/2);

caigNoise = ...
    sigmaCAIG ...
    *randn(NCAIG,3);

OmegaCAIG = ...
    OmegaA_CAIG ...
    +caigNoise;

fprintf('CAIG MODEL\n');
fprintf('--------------------------------------------\n');

fprintf('sigma_CAIG = %.6e rad/s\n\n', ...
    sigmaCAIG);

%% ============================================================
% 8. CREATE TIMETABLES
% =============================================================

TT_FOG = ...
    timetable( ...
        OmegaFOG(:,1), ...
        OmegaFOG(:,2), ...
        OmegaFOG(:,3), ...
        ...
        'RowTimes', ...
        timeFOG, ...
        ...
        'VariableNames',{ ...
            'OmegaX', ...
            'OmegaY', ...
            'OmegaZ'});

TT_CAIG = ...
    timetable( ...
        OmegaCAIG(:,1), ...
        OmegaCAIG(:,2), ...
        OmegaCAIG(:,3), ...
        ...
        'RowTimes', ...
        timeCAIG, ...
        ...
        'VariableNames',{ ...
            'OmegaX', ...
            'OmegaY', ...
            'OmegaZ'});

%% ============================================================
% 9. RETIME FOG TO CAIG EPOCHS
% =============================================================

TT_FOG_at_CAIG = ...
    retime( ...
        TT_FOG, ...
        TT_CAIG.Properties.RowTimes, ...
        'linear');

OmegaFOG_at_CAIG = ...
    [ ...
        TT_FOG_at_CAIG.OmegaX, ...
        TT_FOG_at_CAIG.OmegaY, ...
        TT_FOG_at_CAIG.OmegaZ
    ];

%% ============================================================
% 10. ZHANG OBSERVATION
% =============================================================

% z_k =
%
% Omega_FOG - Omega_CAIG

deltaOmega = ...
    OmegaFOG_at_CAIG ...
    -OmegaCAIG;

%% ============================================================
% 11. MEASUREMENT COVARIANCE R
% =============================================================

sigmaZ = ...
    sqrt( ...
        sigmaFOG^2 ...
        +sigmaCAIG^2);

R = ...
    sigmaZ^2 ...
    *eye(3);

fprintf('MEASUREMENT MODEL\n');
fprintf('--------------------------------------------\n');

fprintf('sigma_Z    = %.6e rad/s\n', ...
    sigmaZ);

fprintf('R diagonal = %.6e (rad/s)^2\n\n', ...
    R(1,1));

%% ============================================================
% 12. INITIAL CONDITIONS
% =============================================================

X0 = ...
    zeros(6,1);

phiStd0 = ...
    deg2rad([1;2;3]);

biasStd0 = ...
    deg2rad([0.1;0.1;0.1]) ...
    /3600;

P0 = ...
    diag( ...
        [phiStd0;biasStd0].^2);

Phi = ...
    eye(6);

Q = ...
    zeros(6);

I6 = ...
    eye(6);

%% ============================================================
% 13. MANUAL FILTER INITIALIZATION
% =============================================================

Xmanual = ...
    X0;

Pmanual = ...
    P0;

XmanualHistory = ...
    zeros(NCAIG,6);

PmanualHistory = ...
    zeros(NCAIG,6);

%% ============================================================
% 14. trackingKF INITIALIZATION
% =============================================================

omega0 = ...
    OmegaA_CAIG(1,:).';

H0 = ...
    [ ...
        skewMatrix(omega0), ...
        eye(3)
    ];

% Custom linear MATLAB Kalman filter:
%
% x(k+1) = Phi*x(k) + w(k)
%
% z(k)   = H(k)*x(k) + v(k)

KF = ...
    trackingKF( ...
        Phi, ...
        H0, ...
        ...
        'State', ...
        X0, ...
        ...
        'StateCovariance', ...
        P0, ...
        ...
        'ProcessNoise', ...
        Q, ...
        ...
        'MeasurementNoise', ...
        R);

XmatlabHistory = ...
    zeros(NCAIG,6);

PmatlabHistory = ...
    zeros(NCAIG,6);

%% ============================================================
% 15. DIFFERENCE STORAGE
% =============================================================

stateDifferenceHistory = ...
    zeros(NCAIG,6);

covDifferenceHistory = ...
    zeros(NCAIG,1);

%% ============================================================
% 16. RUN BOTH FILTERS IN PARALLEL
% =============================================================

for k = 1:NCAIG

    %% --------------------------------------------------------
    % SAME H_k FOR BOTH FILTERS
    % ---------------------------------------------------------

    omega = ...
        OmegaA_CAIG(k,:).';

    Hk = ...
        [ ...
            skewMatrix(omega), ...
            eye(3)
        ];

    z = ...
        deltaOmega(k,:).';

    %% ========================================================
    % A. CURRENT MANUAL KALMAN
    % =========================================================

    % Prediction

    XpredManual = ...
        Phi ...
        *Xmanual;

    PpredManual = ...
        Phi ...
        *Pmanual ...
        *Phi.' ...
        +Q;

    % Innovation

    innovationManual = ...
        z ...
        -Hk*XpredManual;

    % Innovation covariance

    Smanual = ...
        Hk ...
        *PpredManual ...
        *Hk.' ...
        +R;

    % Kalman gain

    Kmanual = ...
        PpredManual ...
        *Hk.' ...
        /Smanual;

    % State correction

    Xmanual = ...
        XpredManual ...
        +Kmanual ...
        *innovationManual;

    % Joseph covariance update

    Pmanual = ...
        (I6-Kmanual*Hk) ...
        *PpredManual ...
        *(I6-Kmanual*Hk).' ...
        ...
        +Kmanual ...
        *R ...
        *Kmanual.';

    %% ========================================================
    % B. MATLAB trackingKF
    % =========================================================

    % H is time-varying but always 3 x 6.
    %
    % Only its numerical values are changed.

    KF.MeasurementModel = ...
        Hk;

    % Prediction:
    %
    % State     <- Phi * State
    %
    % Covariance <- Phi*P*Phi' + Q

    predict(KF);

    % Correction using the exact same z_k

    [Xmatlab,Pmatlab] = ...
        correct( ...
            KF, ...
            z);

    %% ========================================================
    % STORE
    % =========================================================

    XmanualHistory(k,:) = ...
        Xmanual.';

    PmanualHistory(k,:) = ...
        diag(Pmanual).';

    XmatlabHistory(k,:) = ...
        Xmatlab.';

    PmatlabHistory(k,:) = ...
        diag(Pmatlab).';

    stateDifferenceHistory(k,:) = ...
        Xmanual.' ...
        -Xmatlab.';

    covDifferenceHistory(k) = ...
        max( ...
            abs( ...
                Pmanual(:) ...
                -Pmatlab(:)));

end

